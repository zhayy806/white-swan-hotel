def rebuild():
    print("=" * 60)
    print("🔧 FAQ 细粒度分块重建")
    print("=" * 60)

    persist_dir = config.CHROMA_DIR
    embedding = HuggingFaceEmbeddings(
        model_name=config.EMBEDDING_MODEL,
        model_kwargs={"device": "cpu"},
        encode_kwargs={"normalize_embeddings": True},
    )
    vs = Chroma(persist_directory=persist_dir, embedding_function=embedding)

    before = vs._collection.count()

    # 1. 删除旧FAQ文档
    try:
        old_faq_ids = vs._collection.get(where={"source": "hotel_faq"})["ids"]
        if old_faq_ids:
            vs._collection.delete(ids=old_faq_ids)
            print(f"🗑️  删除旧FAQ块: {len(old_faq_ids)} 个")
    except Exception as e:
        print(f"⚠️  删除旧FAQ失败: {e}")

    # 2. 构建新Document
    docs = []
    for section, keywords, content in FAQ_CHUNKS:
        docs.append(Document(
            page_content=content,
            metadata={
                "source": "hotel_faq",
                "hotel_name": "白天鹅宾馆",
                "section": section,
                "topic_keywords": keywords,
                "doc_type": "faq",
            }
        ))

    # 3. 分批插入
    batch_size = 5
    for i in range(0, len(docs), batch_size):
        batch = docs[i:i + batch_size]
        vs.add_documents(batch)
        done = min(i + batch_size, len(docs))
        print(f"  ⏳ 入库 {done}/{len(docs)} 个FAQ块", end="\r")

    after = vs._collection.count()
    print(f"\n✅ FAQ重建完成: {len(docs)} 个细粒度块")
    print(f"   向量库: {before} → {after} (净变化 {after - before})")

    # 4. 按类别统计
    from collections import Counter
    section_counts = Counter(d.metadata["section"] for d in docs)
    print(f"\n📂 按章节分布:")
    for sec, cnt in section_counts.most_common():
        print(f"   {sec}: {cnt}块")

    return vs, docs


def quick_test(vs):
    """快速验证之前未命中的4个查询"""
    tests = [
        ("停车是否收费", "停车"),
        ("回南天潮湿怎么办", "天气"),
        ("有无充电桩", "充电桩"),
        ("行政酒廊值不值得升级", "行政酒廊"),
        ("一次性用品能带走吗", "一次性用品"),
        ("北方人吃得惯粤菜吗", "北方口味"),
        ("房间隔音怎么样", "隔音"),
        ("酒店有什么缺点", "缺点"),
    ]
    print(f"\n{'='*60}")
    print("🔍 重建后验证（之前未命中的查询）")
    print(f"{'='*60}")
    all_hit = True
    for q, expected_topic in tests:
        docs = vs.similarity_search(q, k=2, filter={"source": "hotel_faq"})
        sections = [d.metadata.get("section", "") for d in docs]
        hit = any(expected_topic in sec for sec in sections)
        status = f"✅ #{sections.index([s for s in sections if expected_topic in s][0])+1}" if hit else "❌"
        if not hit:
            all_hit = False
        print(f"  {status} {q:<20} → {[s[:20] for s in sections]}")
    if all_hit:
        print(f"\n  🎉 全部命中！")


if __name__ == "__main__":
    vs, docs = rebuild()
    quick_test(vs)
